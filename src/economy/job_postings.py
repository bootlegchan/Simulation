"""
Dynamic Job Postings & Dual-Channel Labor Dispatch Engine.
Generates dynamic employment opportunities where need arises across the settlement:
1. Official Channels:
   - Posted on public notice boards (village square, town hall, market stalls).
   - Generated by civic demand (night watch, infrastructure repair, sanitation)
     or commercial surges (tavern servers, harvest hands, bakery helpers).
   - Fully lawful, verified, taxed proportionally, and builds civic reputation.
2. Illicit Channels:
   - Posted covertly in underworld hideouts, vice dens, back alleys, or whispered in tavern corners.
   - Generated by shadow syndicates and desperate actors (contraband smuggling,
     debt enforcement muscle, warehouse burglary lookouts, moonshine runners, dead-drop couriers).
   - High-yield cash bounties, tax-free, but carries moral erosion and risk of watch interception.
3. Intelligent Agent Discovery & Decision:
   - Evaluates moral resistance, financial desperation, physical stamina, and vocational affinity
     without implicit hardcoded state machines.
"""
from dataclasses import dataclass, field
from enum import Enum
import math
from typing import Any, Dict, List, Optional, Set, Tuple
import uuid

from src.entities.npc import NPC


class PostingChannel(Enum):
    OFFICIAL = "OFFICIAL"  # Town notice boards, civic bulletins, public guild boards
    ILLICIT = "ILLICIT"    # Underworld chalk marks, vice den whispers, smugglers' drops


class JobPostingCategory(Enum):
    # Official Categories
    CIVIC_WATCH_PATROL = "CIVIC_WATCH_PATROL"
    INFRASTRUCTURE_REPAIR = "INFRASTRUCTURE_REPAIR"
    COMMERCIAL_ASSISTANCE = "COMMERCIAL_ASSISTANCE"
    AGRICULTURAL_HARVEST = "AGRICULTURAL_HARVEST"
    PUBLIC_HEALTH_SANITATION = "PUBLIC_HEALTH_SANITATION"
    SUPPLY_CHAIN_REQUISITION = "SUPPLY_CHAIN_REQUISITION"

    # Illicit Categories
    CONTRABAND_SMUGGLING = "CONTRABAND_SMUGGLING"
    DEBT_ENFORCEMENT_MUSCLE = "DEBT_ENFORCEMENT_MUSCLE"
    BURGLARY_LOOKOUT = "BURGLARY_LOOKOUT"
    ILLICIT_DISTILLATION = "ILLICIT_DISTILLATION"
    BLACKMAIL_DEAD_DROP = "BLACKMAIL_DEAD_DROP"
    FENCE_RUNNER = "FENCE_RUNNER"


class JobPostingStatus(Enum):
    OPEN = "OPEN"
    CLAIMED = "CLAIMED"
    COMPLETED = "COMPLETED"
    EXPIRED = "EXPIRED"
    INTERCEPTED = "INTERCEPTED"


@dataclass
class JobPostingRecord:
    posting_id: str
    title: str
    description: str
    channel: PostingChannel
    category: JobPostingCategory
    employer_id: Optional[str]
    employer_name: str
    location_id: str              # Where the job is posted / discovered
    target_work_location_id: str  # Where the labor is performed
    reward_gold: float
    wage_multiplier: float = 1.0
    required_skill: Optional[str] = None
    min_skill_level: float = 0.0
    risk_tier: int = 0            # 0 = Legal, 1 = Misdemeanor, 2 = Serious felony, 3 = High treason
    duration_ticks: int = 240     # Expected shift / task duration (ticks)
    created_tick: int = 0
    expires_tick: int = 1440      # Expiration timestamp
    status: JobPostingStatus = JobPostingStatus.OPEN
    assigned_worker_id: Optional[str] = None
    assigned_worker_name: Optional[str] = None
    work_ticks_elapsed: int = 0
    is_covert: bool = False
    priority_score: float = 1.0
    urgency_level: float = 0.0
    recipe_id: Optional[str] = None
    required_commodity: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "posting_id": self.posting_id,
            "title": self.title,
            "description": self.description,
            "channel": self.channel.value,
            "category": self.category.value,
            "employer_id": self.employer_id,
            "employer_name": self.employer_name,
            "location_id": self.location_id,
            "target_work_location_id": self.target_work_location_id,
            "reward_gold": round(self.reward_gold, 2),
            "wage_multiplier": round(self.wage_multiplier, 2),
            "required_skill": self.required_skill,
            "min_skill_level": self.min_skill_level,
            "risk_tier": self.risk_tier,
            "duration_ticks": self.duration_ticks,
            "created_tick": self.created_tick,
            "expires_tick": self.expires_tick,
            "status": self.status.value,
            "assigned_worker_id": self.assigned_worker_id,
            "assigned_worker_name": self.assigned_worker_name,
            "work_ticks_elapsed": self.work_ticks_elapsed,
            "is_covert": self.is_covert,
            "priority_score": round(self.priority_score, 2),
            "urgency_level": round(self.urgency_level, 2),
            "recipe_id": self.recipe_id,
            "required_commodity": self.required_commodity,
        }


class DynamicJobPostingEngine:
    """
    Manages dynamic settlement job postings across official and illicit channels.
    Senses systemic community deficits, creates targeted employment bounties,
    evaluates multi-attribute applicant volition, and resolves contracts.
    """
    _instance: Optional["DynamicJobPostingEngine"] = None

    @classmethod
    def get_instance(cls) -> "DynamicJobPostingEngine":
        if cls._instance is None:
            cls._instance = cls()
        return cls._instance

    def __init__(self):
        self.active_postings: Dict[str, JobPostingRecord] = {}
        self.posting_history: List[JobPostingRecord] = []
        self.total_official_jobs_completed: int = 0
        self.total_illicit_jobs_completed: int = 0
        self.total_illicit_intercepted: int = 0
        self.total_wages_disbursed_gold: float = 0.0

    def create_posting(
        self,
        title: str,
        description: str,
        channel: PostingChannel,
        category: JobPostingCategory,
        location_id: str,
        target_work_location_id: str,
        reward_gold: float,
        employer_id: Optional[str] = None,
        employer_name: str = "Municipal Authority",
        wage_multiplier: float = 1.0,
        required_skill: Optional[str] = None,
        min_skill_level: float = 0.0,
        risk_tier: int = 0,
        duration_ticks: int = 240,
        current_tick: int = 0,
        validity_duration_ticks: int = 1440,
        priority_score: float = 1.0,
        urgency_level: float = 0.0,
        recipe_id: Optional[str] = None,
        required_commodity: Optional[str] = None,
        context: Optional[Any] = None,
    ) -> JobPostingRecord:
        """Publishes a new job posting on the specified channel and location."""
        p_id = f"job_{channel.value.lower()}_{uuid.uuid4().hex[:6]}"
        is_covert = (channel == PostingChannel.ILLICIT)
        posting = JobPostingRecord(
            posting_id=p_id,
            title=title,
            description=description,
            channel=channel,
            category=category,
            employer_id=employer_id,
            employer_name=employer_name,
            location_id=location_id,
            target_work_location_id=target_work_location_id,
            reward_gold=reward_gold,
            wage_multiplier=wage_multiplier,
            required_skill=required_skill,
            min_skill_level=min_skill_level,
            risk_tier=risk_tier,
            duration_ticks=duration_ticks,
            created_tick=current_tick,
            expires_tick=current_tick + validity_duration_ticks,
            status=JobPostingStatus.OPEN,
            is_covert=is_covert,
            priority_score=priority_score,
            urgency_level=urgency_level,
            recipe_id=recipe_id,
            required_commodity=required_commodity,
        )
        self.active_postings[p_id] = posting

        if context and hasattr(context, "publish_event"):
            context.publish_event(
                event_type="job_posting_created",
                source_id="dynamic_job_posting_engine",
                payload=posting.to_dict()
            )

        # Epistemic Contract Atom
        if context and hasattr(context, "get_service"):
            ep_eng = context.get_service("epistemic_engine")
            if ep_eng:
                from src.society.epistemic_engine import EpistemicStatus, VisibilityTier, CarrierType
                is_official = (channel == PostingChannel.OFFICIAL)
                vis_tier = VisibilityTier.PUBLIC_SETTLEMENT if is_official else VisibilityTier.SECRET
                job_atom = ep_eng.create_atom(
                    title=f"Labor Requisition: {title}",
                    content=description,
                    status=EpistemicStatus.FACT,
                    visibility=vis_tier,
                    carrier_type=CarrierType.NOTE,
                    actor_id=employer_id,
                    location_id=location_id,
                    emotional_relevance=1.2,
                    created_tick=current_tick,
                    tags=["job_posting", category.value.lower(), channel.value.lower()],
                    associative_keys=["job", "labor", category.value.lower(), location_id.lower()],
                    payload=posting.to_dict()
                )
                if is_official:
                    ep_eng.post_to_notice_board(location_id, job_atom)

        return posting

    def get_open_postings(
        self,
        channel: Optional[PostingChannel] = None,
        location_id: Optional[str] = None
    ) -> List[JobPostingRecord]:
        """Returns active open postings, optionally filtered by channel or room."""
        res = []
        for p in self.active_postings.values():
            if p.status != JobPostingStatus.OPEN:
                continue
            if channel and p.channel != channel:
                continue
            if location_id and p.location_id != location_id:
                continue
            res.append(p)
        return res

    def evaluate_settlement_needs(self, context: Any, current_tick: int) -> List[JobPostingRecord]:
        """
        Dynamically analyzes settlement state to detect unfulfilled needs and spawn job postings:
        - Official Needs:
          * Public infrastructure decay -> Masonry & Carpenter repair postings.
          * Tavern patron rushes -> Extra Bartender & Server postings.
          * Nocturnal darkness & crime risk -> Deputy Night Watchman postings.
          * Agricultural harvesting / milling -> Harvest hands & flour millers.
          * Sanitation/water pollution -> Cleansing & infirmary assistants.
        - Illicit Needs:
          * Contraband stores ready -> Clandestine moonshine/contraband transport.
          * Wealthy merchants in town -> Warehouse burglary lookout / theft casing.
          * Defaulted loans / debts -> Shadow debt collection & intimidation muscle.
          * Covert secrets ready -> Secret dead-drop letter delivery.
          * Unstaffed still -> Illicit moonshine distillation operator.
        """
        new_postings: List[JobPostingRecord] = []
        hour = (
            context.clock.current_virtual_time.hour
            if hasattr(context, "clock") and context.clock
            else (current_tick // 60) % 24
        )

        from src.configuration.settings import SettingsRegistry
        rules_cfg = SettingsRegistry.get_instance().get("job_posting_rules")
        official_rules = {r["rule_id"]: r for r in rules_cfg.get("official_rules", [])}
        illicit_rules = {r["rule_id"]: r for r in rules_cfg.get("illicit_rules", [])}

        # -----------------------------------------------------------------
        # 1. OFFICIAL CHANNEL POSTINGS (Public Needs)
        # -----------------------------------------------------------------
        public_plaza = context.get_central_public_room() if hasattr(context, "get_central_public_room") else "room_village_square"
        town_halls = context.find_rooms_by_keyword("town_hall") or context.find_rooms_by_building_category("CIVIC") if hasattr(context, "find_rooms_by_keyword") else []
        town_hall = town_halls[0] if town_halls else public_plaza

        # 1a. Tavern / Hospitality Footfall Rush
        tavern_rooms = context.find_rooms_by_keyword("tavern") if hasattr(context, "find_rooms_by_keyword") else []
        if not tavern_rooms and hasattr(context, "find_rooms_by_keyword"):
            tavern_rooms = context.find_rooms_by_keyword("inn")
        if not tavern_rooms and hasattr(context, "find_rooms_by_building_category"):
            tavern_rooms = context.find_rooms_by_building_category("COMMERCIAL")

        for t_room in tavern_rooms:
            patrons = [
                n for n in context.npcs.values()
                if n.location_id == t_room and getattr(n, "is_alive", True)
            ]
            active_servers = [
                n for n in patrons
                if any(k in (n.occupation or "").lower() for k in ("innkeeper", "tavern", "barkeeper", "cook"))
            ]
            has_existing = any(
                p.category == JobPostingCategory.COMMERCIAL_ASSISTANCE and p.target_work_location_id == t_room and p.status in (JobPostingStatus.OPEN, JobPostingStatus.CLAIMED)
                for p in self.active_postings.values()
            )
            if len(patrons) >= 4 and len(active_servers) <= 1 and not has_existing:
                bldg = context.find_building_by_room_id(t_room) if hasattr(context, "find_building_by_room_id") else None
                owner = context.npcs.get(bldg.owner_id) if bldg and bldg.owner_id in context.npcs else None
                emp = owner or context.find_npc_by_role(["innkeeper", "barkeeper", "tavern"])
                emp_name = emp.name if emp else (bldg.name if bldg else "Tavern Hospitality Proprietor")
                emp_id = emp.id if emp else None

                post = self.create_posting(
                    title="Urgent: Tavern Server & Taproom Assistant",
                    description=f"High patron volume at {t_room} requires temporary table service and ale pouring.",
                    channel=PostingChannel.OFFICIAL,
                    category=JobPostingCategory.COMMERCIAL_ASSISTANCE,
                    location_id=public_plaza,
                    target_work_location_id=t_room,
                    reward_gold=6.5,
                    employer_id=None,
                    employer_name="Oakwood Agrarian Council",
                    wage_multiplier=1.4,
                    required_skill="hospitality",
                    duration_ticks=240,
                    current_tick=current_tick,
                    context=context
                )
                new_postings.append(post)

        # 1b. Nocturnal Watch Deficit
        if hour >= 21 or hour < 5:
            active_guards = [
                n for n in context.npcs.values()
                if "guard" in (n.occupation or "").lower() and getattr(n, "current_action", "") in ("LABOR_WORK", "PATROL_STREETS", "SLEEP_REST")
            ]
            has_watch_posting = any(
                p.category == JobPostingCategory.CIVIC_WATCH_PATROL and p.status in (JobPostingStatus.OPEN, JobPostingStatus.CLAIMED)
                for p in self.active_postings.values()
            )
            if len(active_guards) < 2 and not has_watch_posting:
                guard_rooms = context.find_rooms_by_keyword("guard") if hasattr(context, "find_rooms_by_keyword") else []
                if not guard_rooms and hasattr(context, "find_rooms_by_keyword"):
                    guard_rooms = context.find_rooms_by_keyword("watch")
                if not guard_rooms and hasattr(context, "find_rooms_by_building_category"):
                    guard_rooms = context.find_rooms_by_building_category("CIVIC")
                g_room = guard_rooms[0] if guard_rooms else town_hall
                sheriff = context.find_npc_by_role(["sheriff", "captain", "marshal", "commander", "guard"])
                emp_name = sheriff.name if sheriff else "Municipal Watch Command"
                emp_id = sheriff.id if sheriff else None

                post = self.create_posting(
                    title="Municipal Decree: Deputy Night Watch Patrol",
                    description="Nocturnal street patrol and lantern maintenance to safeguard sleeping citizens.",
                    channel=PostingChannel.OFFICIAL,
                    category=JobPostingCategory.CIVIC_WATCH_PATROL,
                    location_id=town_hall,
                    target_work_location_id=g_room,
                    reward_gold=8.0,
                    employer_id=emp_id,
                    employer_name=emp_name,
                    wage_multiplier=1.5,
                    required_skill="brawling",
                    min_skill_level=15.0,
                    duration_ticks=300,
                    current_tick=current_tick,
                    context=context
                )
                new_postings.append(post)

        # 1c. Public Infrastructure Maintenance
        has_repair_posting = any(
            p.category == JobPostingCategory.INFRASTRUCTURE_REPAIR and p.status in (JobPostingStatus.OPEN, JobPostingStatus.CLAIMED)
            for p in self.active_postings.values()
        )
        if not has_repair_posting and hasattr(context, "settlements"):
            worn_bldgs = []
            for sett in context.settlements.values():
                for bldg in sett.buildings.values():
                    if bldg.structural_integrity < 75.0 and bldg.category in ("CIVIC", "CIRCULATION", "COMMERCIAL"):
                        worn_bldgs.append(bldg)
            if worn_bldgs:
                target_bldg = worn_bldgs[0]
                first_room = list(target_bldg.rooms.keys())[0] if target_bldg.rooms else public_plaza
                post = self.create_posting(
                    title=f"Public Works: Masonry & Carpentry Repair at {target_bldg.name}",
                    description=f"Structural wear at {target_bldg.name} requires skilled timber bracing and mortar patching.",
                    channel=PostingChannel.OFFICIAL,
                    category=JobPostingCategory.INFRASTRUCTURE_REPAIR,
                    location_id=public_plaza,
                    target_work_location_id=first_room,
                    reward_gold=7.5,
                    employer_name="Municipal Works Overseer",
                    wage_multiplier=1.3,
                    required_skill="crafting",
                    min_skill_level=15.0,
                    duration_ticks=240,
                    current_tick=current_tick,
                    context=context
                )
                new_postings.append(post)

        # 1d. Agricultural Grain & Milling Surge
        has_agri_posting = any(
            p.category == JobPostingCategory.AGRICULTURAL_HARVEST and p.status in (JobPostingStatus.OPEN, JobPostingStatus.CLAIMED)
            for p in self.active_postings.values()
        )
        sc_eng = context.get_service("supply_chain_engine") if hasattr(context, "get_service") else None
        if not has_agri_posting and sc_eng and hasattr(sc_eng, "get_stock_level"):
            wheat_stock = sc_eng.get_stock_level("raw_wheat")
            flour_stock = sc_eng.get_stock_level("flour")
            if wheat_stock < 5 or flour_stock < 5:
                farm_rooms = context.find_rooms_by_keyword("farm") if hasattr(context, "find_rooms_by_keyword") else []
                if not farm_rooms and hasattr(context, "find_rooms_by_keyword"):
                    farm_rooms = context.find_rooms_by_keyword("mill")
                if not farm_rooms and hasattr(context, "find_rooms_by_building_category"):
                    farm_rooms = context.find_rooms_by_building_category("INDUSTRIAL")
                farm_room = farm_rooms[0] if farm_rooms else public_plaza
                agrarian = context.find_npc_by_role(["farmer", "miller", "agrarian", "yeoman"])
                emp_name = agrarian.name if agrarian else (getattr(list(context.settlements.values())[0], "name", "Settlement") + " Agrarian Council")
                emp_id = agrarian.id if agrarian else None

                post = self.create_posting(
                    title="Harvest Hand: Urgent Grain Milling & Field Labor",
                    description="Low flour stocks require extra hands at the windmill and harvest fields.",
                    channel=PostingChannel.OFFICIAL,
                    category=JobPostingCategory.AGRICULTURAL_HARVEST,
                    location_id=public_plaza,
                    target_work_location_id=farm_room,
                    reward_gold=6.0,
                    employer_id=emp_id,
                    employer_name=emp_name,
                    wage_multiplier=1.25,
                    required_skill="farming",
                    duration_ticks=240,
                    current_tick=current_tick,
                    context=context
                )
                new_postings.append(post)

        # -----------------------------------------------------------------
        # 2. ILLICIT CHANNEL POSTINGS (Covert Shadow Needs with Daily Cooldown)
        # -----------------------------------------------------------------
        last_illicit = getattr(self, "_last_illicit_tick", -9999)
        if (current_tick - last_illicit) < 1440:
            return new_postings

        self._last_illicit_tick = current_tick
        underworld_room = context.find_underworld_room() if hasattr(context, "find_underworld_room") else public_plaza
        vice_rooms = context.find_rooms_by_keyword("vice") or context.find_rooms_by_keyword("den") if hasattr(context, "find_rooms_by_keyword") else []
        vice_den = vice_rooms[0] if vice_rooms else underworld_room

        # 2a. Contraband Smuggling Transit
        has_smuggling = any(
            p.category == JobPostingCategory.CONTRABAND_SMUGGLING and p.status in (JobPostingStatus.OPEN, JobPostingStatus.CLAIMED)
            for p in self.active_postings.values()
        )
        smugglers = [
            n for n in context.npcs.values()
            if any(k in (n.occupation or "").lower() for k in ("smuggler", "outlaw", "scavenger", "thief")) and getattr(n, "is_alive", True)
        ]
        if not has_smuggling and smugglers:
            boss = smugglers[0]
            cellar_rooms = context.find_rooms_by_keyword("cellar") or context.find_rooms_by_keyword("vault") if hasattr(context, "find_rooms_by_keyword") else []
            target_cellar = cellar_rooms[0] if cellar_rooms else public_plaza

            post = self.create_posting(
                title="Cryptic Chalk Mark: Clandestine Keg Run",
                description="Move an uninspected cargo crate from cellar stores to the river landing under cover of darkness.",
                channel=PostingChannel.ILLICIT,
                category=JobPostingCategory.CONTRABAND_SMUGGLING,
                location_id=underworld_room,
                target_work_location_id=target_cellar,
                reward_gold=16.0,
                employer_id=boss.id,
                employer_name=boss.name,
                wage_multiplier=1.4,
                required_skill="subterfuge",
                min_skill_level=10.0,
                risk_tier=2,
                duration_ticks=180,
                current_tick=current_tick,
                context=context
            )
            new_postings.append(post)

        # 2b. Debt Collection & Intimidation Muscle
        has_muscle = any(
            p.category == JobPostingCategory.DEBT_ENFORCEMENT_MUSCLE and p.status in (JobPostingStatus.OPEN, JobPostingStatus.CLAIMED)
            for p in self.active_postings.values()
        )
        defaulters = [
            n for n in context.npcs.values()
            if hasattr(n, "has_tag") and n.has_tag("TAG_KNOWN_DEFAULTER") and getattr(n, "is_alive", True)
        ]
        if not has_muscle and (defaulters or len(context.npcs) >= 10):
            target_target = defaulters[0] if defaulters else list(context.npcs.values())[-1]
            post = self.create_posting(
                title="Discreet Whisper: Debt Collection & Heavy Intimidation",
                description=f"Deliver a severe physical warning to delinquent debtor {target_target.name} and reclaim overdue gold.",
                channel=PostingChannel.ILLICIT,
                category=JobPostingCategory.DEBT_ENFORCEMENT_MUSCLE,
                location_id=vice_den,
                target_work_location_id=target_target.location_id or public_plaza,
                reward_gold=5.5,
                employer_name="Shadow Syndicate Broker",
                wage_multiplier=1.4,
                required_skill="brawling",
                min_skill_level=20.0,
                risk_tier=2,
                duration_ticks=180,
                current_tick=current_tick,
                context=context
            )
            post.target_entity_id = target_target.id
            new_postings.append(post)

        # 2c. Warehouse Burglary Lookout
        has_lookout = any(
            p.category == JobPostingCategory.BURGLARY_LOOKOUT and p.status in (JobPostingStatus.OPEN, JobPostingStatus.CLAIMED)
            for p in self.active_postings.values()
        )
        wealthy_merchants = [
            n for n in context.npcs.values()
            if getattr(n, "wealth", 0.0) >= 60.0 and any(k in (n.occupation or "").lower() for k in ("merchant", "trader", "notary", "noble"))
        ]
        if not has_lookout and wealthy_merchants and hour >= 22:
            target_merchant = wealthy_merchants[0]
            shop_loc = target_merchant.work_location_id or target_merchant.home_location_id or public_plaza
            look_rule = illicit_rules.get("burglary_lookout", {})
            post = self.create_posting(
                title=look_rule.get("title", "Tavern Corner Whisper: Night Lookout for Shop Entry"),
                description=f"Keep watch for town guards at {shop_loc} while the lockbox is quietly pried open.",
                channel=PostingChannel.ILLICIT,
                category=JobPostingCategory.BURGLARY_LOOKOUT,
                location_id=underworld_room,
                target_work_location_id=shop_loc,
                reward_gold=float(look_rule.get("reward_gold", 6.5)),
                employer_name="The Silent Knives",
                wage_multiplier=float(look_rule.get("wage_multiplier", 1.4)),
                required_skill=look_rule.get("required_skill", "subterfuge"),
                min_skill_level=float(look_rule.get("min_skill_level", 15.0)),
                risk_tier=int(look_rule.get("risk_tier", 2)),
                duration_ticks=int(look_rule.get("duration_ticks", 180)),
                current_tick=current_tick,
                context=context
            )
            post.target_entity_id = target_merchant.id
            new_postings.append(post)

        return new_postings

    def evaluate_npc_job_seeking(
        self,
        npc: NPC,
        visible_postings: List[JobPostingRecord],
        context: Any
    ) -> Optional[Tuple[JobPostingRecord, float, str]]:
        """
        Evaluates which job posting (official or illicit) an NPC wants to claim based on:
        1. Somatic fatigue: Energy < 20 cannot accept labor.
        2. Moral resistance & Channel alignment:
           - Upright/honorable NPCs (Honor > 0.65, Crime Propensity < 15) REJECT illicit postings.
           - Criminals and desperate rogues actively seek illicit jobs for the high cash payout.
        3. Financial urgency: Poorer NPCs have higher motivation to take jobs.
        4. Skill and vocational match.
        """
        # Clergy dedication check: Sacred role supports community and never seeks external jobs
        occ_l = (getattr(npc, "occupation", "") or "").lower()
        if any(k in occ_l for k in ("priest", "clergy", "monk", "curate")):
            return None

        energy = float(npc.needs.get("energy", 100.0))
        if energy < 20.0:
            return None

        wealth = float(getattr(npc, "wealth", 0.0))
        p = getattr(npc, "personality", {}) or {}
        sp = getattr(npc, "social_profile", {}) or {}
        v = getattr(npc, "vices", {}) or {}

        honor = float(sp.get("moral_values", {}).get("honor", 0.5))
        crime_prop = float(v.get("crime_propensity", 0.0))
        conscientiousness = float(p.get("conscientiousness", 0.5))
        agreeableness = float(p.get("agreeableness", 0.5))

        # Elastic Maslow Desire: Financial urgency scaling
        desire_eng = context.get_service("desire_hierarchy_engine") if (context and hasattr(context, "get_service")) else None
        if desire_eng and hasattr(desire_eng, "evaluate_agent_hierarchy"):
            desire_prof = desire_eng.evaluate_agent_hierarchy(npc, context, getattr(context.clock, "current_tick", 0) if (hasattr(context, "clock") and context.clock) else 0)
            fin_urgency = desire_prof.financial_urgency_factor
        else:
            if wealth < 15.0:
                fin_urgency = 1.0 + (((15.0 - wealth) / 15.0) ** 1.5) * 1.5
            elif wealth < 120.0:
                ratio = (wealth - 15.0) / 105.0
                fin_urgency = max(0.03, 1.0 - (ratio ** 1.2))
            else:
                fin_urgency = 0.03

        # Financial pressure score (0 to 40)
        poverty_strain = max(0.0, min(40.0, (40.0 - wealth)))

        candidates: List[Tuple[JobPostingRecord, float, str]] = []

        for post in visible_postings:
            if post.status != JobPostingStatus.OPEN:
                continue

            # Skill check
            if post.required_skill and post.min_skill_level > 0:
                skill_val = npc.get_skill(post.required_skill) if hasattr(npc, "get_skill") else 10.0
                if skill_val < post.min_skill_level:
                    volition_eng = context.get_service("means_end_volition_engine") if (context and hasattr(context, "get_service")) else None
                    if volition_eng:
                        amb = float(getattr(npc, "mental_attributes", {}).get("ambition", 50.0))
                        if amb >= 40.0:
                            cur_t = getattr(context.clock, "current_tick", 0) if (hasattr(context, "clock") and context.clock) else 0
                            volition_eng.register_career_aspiration(
                                npc,
                                target_occupation=post.title,
                                required_skill=post.required_skill,
                                required_level=post.min_skill_level,
                                current_level=skill_val,
                                current_tick=cur_t
                            )
                    continue  # Lacks necessary competence right now

            # Channel Evaluation
            if post.channel == PostingChannel.OFFICIAL:
                # Criminal probation check: convicts on watch probation cannot apply for official civic jobs!
                prob_until = getattr(npc, "criminal_probation_until_tick", 0)
                cur_tick = getattr(context.clock, "current_tick", 0) if (hasattr(context, "clock") and context.clock) else 0
                has_crim_tag = hasattr(npc, "has_tag") and npc.has_tag("TAG_CONVICTED_CRIMINAL")
                if (cur_tick < prob_until) or has_crim_tag:
                    continue  # Barred from municipal employment while on probation

                # Upright, conscientious, and lawful citizens favor official postings
                civic_affinity = (conscientiousness * 25.0) + (honor * 20.0) + (agreeableness * 15.0)
                pri_mult = getattr(post, "priority_score", 1.0)
                
                # Check if this is menial casual labor
                is_menial = post.category in (JobPostingCategory.COMMERCIAL_ASSISTANCE, JobPostingCategory.PUBLIC_HEALTH_SANITATION)
                reward_pull = (post.reward_gold * post.wage_multiplier * 2.5 * pri_mult)

                if is_menial:
                    # Affluent citizens ignore menial odd jobs
                    reward_pull *= fin_urgency
                    occ_l = (npc.occupation or "").lower()
                    if any(k in occ_l for k in ("baker", "smith", "blacksmith", "carpenter", "mayor", "notary", "priest")) and wealth > 60.0:
                        civic_affinity *= 0.20

                score = reward_pull + (poverty_strain * fin_urgency) + civic_affinity

                if is_menial and wealth > 80.0 and score < 30.0:
                    continue

                reason = f"Applied for official job '{post.title}' at {post.target_work_location_id} (wage {post.reward_gold * post.wage_multiplier:.1f}g, priority {pri_mult:.1f}x)"
                candidates.append((post, score, reason))

            elif post.channel == PostingChannel.ILLICIT:
                # Moral filter: Upright citizens will not commit crimes
                effective_honor = honor * (1.0 - (crime_prop / 100.0) * 0.75)
                illicit_affinity = (crime_prop * 0.60) + ((1.0 - effective_honor) * 35.0) + (poverty_strain * 0.70)
                if (effective_honor > 0.65 and crime_prop < 25.0) or illicit_affinity < 25.0:
                    continue  # Moral conscience refuses illicit contract

                # Criminal or desperate character jumps at the high reward
                score = (post.reward_gold * 3.5) + illicit_affinity + (poverty_strain * 1.2)
                reason = f"Accepted illicit underworld contract '{post.title}' for {post.reward_gold:.1f}g bounty"
                candidates.append((post, score, reason))

        if candidates:
            candidates.sort(key=lambda x: x[1], reverse=True)
            return candidates[0]

        return None

    def claim_job_posting(
        self,
        posting_id: str,
        worker: NPC,
        context: Any,
        current_tick: int
    ) -> Dict[str, Any]:
        """Worker formally claims an open job posting and moves to the worksite."""
        # Clergy cannot claim secular/casual postings
        occ_l = (getattr(worker, "occupation", "") or "").lower()
        if any(k in occ_l for k in ("priest", "clergy", "monk", "curate")):
            return {"success": False, "reason": "Clergy is dedicated solely to sacred parish duties"}

        post = self.active_postings.get(posting_id)
        if not post or post.status != JobPostingStatus.OPEN:
            return {"success": False, "reason": "Posting not found or no longer open"}

        if post.channel == PostingChannel.OFFICIAL:
            prob_until = getattr(worker, "criminal_probation_until_tick", 0)
            cur_tick = getattr(context.clock, "current_tick", 0) if (hasattr(context, "clock") and context.clock) else current_tick
            has_crim_tag = hasattr(worker, "has_tag") and worker.has_tag("TAG_CONVICTED_CRIMINAL")
            if (cur_tick < prob_until) or has_crim_tag:
                return {"success": False, "reason": "Applicant is on active criminal probation and barred from municipal employment."}

        post.status = JobPostingStatus.CLAIMED
        post.assigned_worker_id = worker.id
        post.assigned_worker_name = worker.name
        post.work_ticks_elapsed = 0

        # Move worker to target location
        worker.location_id = post.target_work_location_id
        worker.current_action = f"JOB_{post.category.value}"

        time_iso = (
            context.clock.current_virtual_time_iso
            if hasattr(context, "clock") and context.clock
            else f"Tick {current_tick}"
        )

        bio_cat = "CIVIC_EMPLOYMENT" if post.channel == PostingChannel.OFFICIAL else "ILLICIT_OPERATION"
        worker.record_biographical_entry(
            current_tick, time_iso, bio_cat,
            f"Contracted for {post.channel.value.lower()} assignment '{post.title}' in {post.target_work_location_id} (Reward: {post.reward_gold:.1f}g).",
            {"posting_id": post.posting_id, "channel": post.channel.value, "reward": post.reward_gold}
        )

        if hasattr(context, "publish_event"):
            context.publish_event(
                event_type="job_posting_claimed",
                source_id="dynamic_job_posting_engine",
                payload={"posting_id": post.posting_id, "worker_id": worker.id, "worker_name": worker.name, "channel": post.channel.value, "tick": current_tick}
            )

        return {"success": True, "posting": post.to_dict()}

    def complete_job_posting(
        self,
        posting_id: str,
        worker: NPC,
        context: Any,
        current_tick: int
    ) -> Dict[str, Any]:
        """Resolves a completed job posting, handles compensation, taxation, and crime detection risks."""
        post = self.active_postings.get(posting_id)
        if not post or post.status != JobPostingStatus.CLAIMED:
            return {"success": False, "reason": "Posting not in progress"}

        reward = post.reward_gold * post.wage_multiplier
        time_iso = (
            context.clock.current_virtual_time_iso
            if hasattr(context, "clock") and context.clock
            else f"Tick {current_tick}"
        )

        if post.channel == PostingChannel.OFFICIAL:
            # 1. Official Completion
            # Disburse funds from employer or Municipal Treasury
            treasury = getattr(context, "municipal_treasury", None)
            if post.employer_id and post.employer_id in context.npcs:
                emp = context.npcs[post.employer_id]
                actual_payout = min(emp.wealth, reward)
                emp.wealth = max(0.0, round(emp.wealth - actual_payout, 2))
            elif treasury and hasattr(treasury, "balance") and treasury.balance >= reward:
                treasury.balance = round(treasury.balance - reward, 2)
                actual_payout = reward
            else:
                actual_payout = reward  # Backed by civic credit

            worker.wealth = round(worker.wealth + actual_payout, 2)
            if hasattr(worker, "record_stat"):
                worker.record_stat("career_earnings_gold", actual_payout)

            # Legitimate earnings are tracked for proportional income tax via worker.wealth setter

            # If this was a supply chain requisition, execute the physical production step
            if post.category == JobPostingCategory.SUPPLY_CHAIN_REQUISITION and getattr(post, "recipe_id", None):
                sc_eng = context.get_service("supply_chain_engine") if hasattr(context, "get_service") else None
                if sc_eng and hasattr(sc_eng, "execute_production_step"):
                    sc_eng.execute_production_step(worker, post.recipe_id, context, tick=current_tick)

            worker.adjust_feeling("contentment", 15.0)
            worker.adjust_feeling("pride", 10.0)
            worker.adjust_feeling("stress", -8.0)
            worker.needs["energy"] = max(0.0, worker.needs.get("energy", 100.0) - 15.0)

            post.status = JobPostingStatus.COMPLETED
            self.total_official_jobs_completed += 1
            self.total_wages_disbursed_gold += actual_payout

            worker.record_biographical_entry(
                current_tick, time_iso, "CIVIC_EMPLOYMENT",
                f"Successfully completed official assignment '{post.title}'; earned {actual_payout:.1f} gold.",
                {"payout": actual_payout, "channel": "OFFICIAL"}
            )

            outcome = {"success": True, "status": "COMPLETED", "payout_gold": actual_payout, "intercepted": False}

        else:
            # 2. Illicit Completion (Crime Risk & Watch Interception)
            # Check for Town Watch interception
            sheriff = context.find_npc_by_role(["sheriff", "guard", "constable", "watchman"])
            active_watch_in_area = False
            if sheriff and sheriff.location_id == post.target_work_location_id:
                active_watch_in_area = True

            detection_chance = 0.35 if active_watch_in_area else (0.10 * post.risk_tier)
            subterfuge_skill = worker.get_skill("subterfuge") if hasattr(worker, "get_skill") else 10.0
            detection_chance = max(0.05, min(0.70, detection_chance - (subterfuge_skill * 0.005)))

            is_intercepted = (context.random.random() < detection_chance)

            if is_intercepted:
                post.status = JobPostingStatus.INTERCEPTED
                self.total_illicit_intercepted += 1

                # Watch intercepts the criminal operation!
                penalty_fine = min(worker.wealth, round(reward * 1.5, 2))
                worker.wealth = max(0.0, round(worker.wealth - penalty_fine, 2))
                treasury = getattr(context, "municipal_treasury", None)
                if treasury and hasattr(treasury, "balance") and penalty_fine > 0:
                    treasury.balance = round(treasury.balance + penalty_fine, 2)

                # Set 3-day criminal probation (4320 ticks) & status tag
                worker.criminal_probation_until_tick = current_tick + 4320
                if hasattr(worker, "add_status_tag"):
                    worker.add_status_tag("TAG_CONVICTED_CRIMINAL")

                worker.adjust_moral_erosion(2.0)
                worker.adjust_feeling("stress", 35.0)
                worker.adjust_feeling("guilt", 20.0)

                worker.record_biographical_entry(
                    current_tick, time_iso, "ILLICIT_INTERCEPTION",
                    f"Caught red-handed during illicit contract '{post.title}' by the town watch! Fined {penalty_fine:.1f}g.",
                    {"penalty_fine": penalty_fine, "risk_tier": post.risk_tier}
                )

                if hasattr(context, "publish_event"):
                    context.publish_event(
                        event_type="illicit_job_intercepted",
                        source_id="dynamic_job_posting_engine",
                        payload={"posting_id": post.posting_id, "worker_id": worker.id, "fine_gold": penalty_fine, "tick": current_tick}
                    )

                outcome = {"success": False, "status": "INTERCEPTED", "penalty_fine": penalty_fine, "intercepted": True}

            else:
                # Successfully pulled off the illicit heist / delivery!
                # Closed-loop: Gold is looted/extorted from victim or criminal boss, not magically minted!
                actual_payout = reward
                target_id = getattr(post, "target_entity_id", None)
                target_npc = context.npcs.get(target_id) if (target_id and hasattr(context, "npcs")) else None

                if post.category == JobPostingCategory.BURGLARY_LOOKOUT and target_npc:
                    if target_npc.wealth > 15.0:
                        actual_payout = min(target_npc.wealth - 15.0, reward)
                        target_npc.wealth = round(target_npc.wealth - actual_payout, 2)
                    else:
                        actual_payout = min(4.0, reward * 0.4)
                elif post.category == JobPostingCategory.DEBT_ENFORCEMENT_MUSCLE and target_npc:
                    if target_npc.wealth > 10.0:
                        actual_payout = min(target_npc.wealth - 10.0, reward)
                        target_npc.wealth = round(target_npc.wealth - actual_payout, 2)
                    else:
                        actual_payout = min(3.5, reward * 0.4)
                elif post.employer_id and hasattr(context, "npcs") and post.employer_id in context.npcs:
                    boss = context.npcs[post.employer_id]
                    if boss.wealth > 15.0:
                        actual_payout = min(boss.wealth - 15.0, reward)
                        boss.wealth = round(boss.wealth - actual_payout, 2)
                    else:
                        actual_payout = min(4.0, reward * 0.4)
                else:
                    actual_payout = reward

                worker.wealth = round(worker.wealth + actual_payout, 2)

                # Town Watch increases alertness following illicit activity
                sheriff = context.find_npc_by_role(["sheriff", "guard", "constable", "watchman"]) if hasattr(context, "find_npc_by_role") else None
                if sheriff and hasattr(sheriff, "adjust_feeling"):
                    sheriff.adjust_feeling("vigilance", 12.0)

                # Illicit earnings bypass tax reporting (tax-free!)
                if hasattr(worker, "record_stat"):
                    worker.record_stat("crimes_committed", 1)

                worker.adjust_moral_erosion(1.5 * post.risk_tier)
                worker.adjust_feeling("pride", 15.0)  # Criminal thrill
                worker.adjust_feeling("guilt", 10.0)
                worker.needs["energy"] = max(0.0, worker.needs.get("energy", 100.0) - 20.0)

                post.status = JobPostingStatus.COMPLETED
                self.total_illicit_jobs_completed += 1
                self.total_wages_disbursed_gold += actual_payout

                worker.record_biographical_entry(
                    current_tick, time_iso, "ILLICIT_OPERATION",
                    f"Successfully executed clandestine contract '{post.title}'; pocketed {actual_payout:.1f}g tax-free black market gold.",
                    {"bounty": actual_payout, "channel": "ILLICIT", "risk_tier": post.risk_tier}
                )

                outcome = {"success": True, "status": "COMPLETED", "payout_gold": actual_payout, "intercepted": False}

        self.posting_history.append(post)
        del self.active_postings[posting_id]

        if hasattr(context, "publish_event"):
            context.publish_event(
                event_type="job_posting_completed",
                source_id="dynamic_job_posting_engine",
                payload={"posting_id": post.posting_id, "worker_id": worker.id, "channel": post.channel.value, "status": post.status.value, "tick": current_tick}
            )

        return outcome

    def process_posting_lifecycle(self, context: Any, current_tick: int) -> Dict[str, int]:
        """
        Hourly/periodic lifecycle maintenance:
        - Advances work ticks for claimed jobs and resolves completion.
        - Expires stale postings past their expiration timestamp.
        """
        expired_count = 0
        completed_count = 0

        for p_id in list(self.active_postings.keys()):
            post = self.active_postings[p_id]

            if post.status == JobPostingStatus.OPEN:
                if current_tick >= post.expires_tick:
                    post.status = JobPostingStatus.EXPIRED
                    self.posting_history.append(post)
                    del self.active_postings[p_id]
                    expired_count += 1

            elif post.status == JobPostingStatus.CLAIMED:
                post.work_ticks_elapsed += 60  # Advance hourly increment
                if post.work_ticks_elapsed >= post.duration_ticks:
                    worker = context.npcs.get(post.assigned_worker_id) if post.assigned_worker_id else None
                    if worker:
                        self.complete_job_posting(p_id, worker, context, current_tick)
                        completed_count += 1
                    else:
                        post.status = JobPostingStatus.EXPIRED
                        del self.active_postings[p_id]
                        expired_count += 1

        return {"expired_count": expired_count, "completed_count": completed_count}

    def get_job_statistics(self) -> Dict[str, Any]:
        """Returns macro telemetry for the job market."""
        return {
            "active_open_postings": sum(1 for p in self.active_postings.values() if p.status == JobPostingStatus.OPEN),
            "active_claimed_postings": sum(1 for p in self.active_postings.values() if p.status == JobPostingStatus.CLAIMED),
            "total_official_completed": self.total_official_jobs_completed,
            "total_illicit_completed": self.total_illicit_jobs_completed,
            "total_illicit_intercepted": self.total_illicit_intercepted,
            "total_wages_disbursed_gold": round(self.total_wages_disbursed_gold, 2),
            "total_history_count": len(self.posting_history),
        }
